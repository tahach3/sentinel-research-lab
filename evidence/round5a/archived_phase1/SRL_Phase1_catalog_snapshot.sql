-- =====================================================================
-- SENTINEL RESEARCH LAB — PHASE 1 — SCHEMA-8 CATALOG EVIDENCE BUNDLE
-- =====================================================================
-- Purpose : read-only extraction of authoritative schema-8 catalog state
-- Closes  : Codex findings #1 (function ACLs), #2 (role/table matrix),
--           #3 (preflight expected inventories)
-- Mode    : READ ONLY. Executes no DDL, no DML, no locks, no temp objects.
-- Safety  : uses ONLY pg_catalog and built-in functions. Never calls any
--           research.* function, so evidence is not generated by the code
--           under review.
--
-- EXECUTION
--   Run the WHOLE FILE in ONE session, ONE transaction, ending in ROLLBACK.
--   Sections are separated by banner comments and may be read individually,
--   but must not be executed in separate transactions: the start/end drift
--   digests (G00/G99) are only meaningful across a single snapshot.
--
--   psql --no-psqlrc --set ON_ERROR_STOP=1 -f SRL_Phase1_catalog_snapshot.sql
--
--   Capture stdout/stderr as raw bytes, decode UTF-8 explicitly.
--
-- HARD FLOOR
--   PostgreSQL 11+. G01 returns BLOCKED if lower. Below 11 there is no
--   built-in sha256() and pg_proc.prokind does not exist; the bundle is
--   not valid and must not be adapted by hand.
--
-- TARGET SCHEMA
--   'research' throughout. It appears as a literal in every WHERE clause
--   deliberately — no variable, no substitution, no room to widen scope.
-- =====================================================================


-- =====================================================================
-- READ-ONLY PREAMBLE  (mandatory, do not remove)
-- =====================================================================
SET default_transaction_read_only = on;

BEGIN;
SET TRANSACTION READ ONLY, ISOLATION LEVEL REPEATABLE READ;
SET LOCAL statement_timeout                     = '120s';
SET LOCAL lock_timeout                          = '5s';
SET LOCAL idle_in_transaction_session_timeout   = '300s';
SET LOCAL search_path                           = pg_catalog;

-- Note on isolation: REPEATABLE READ stabilises user-issued SELECTs against
-- catalog tables. It does NOT stabilise has_*_privilege(), which performs
-- internal syscache lookups and may observe fresher state. The G00/G99 drift
-- digest pair is the actual guarantee that nothing changed mid-capture.


-- =====================================================================
-- G00 — DRIFT DIGEST (START)                       EV-DRIFT-001
-- =====================================================================
-- Proves: the catalog did not change during capture (compare to G99).
-- Row key: none, single value.
SELECT
  'EV-DRIFT-001'                                    AS evidence_set,
  'start'                                           AS position,
  encode(sha256(convert_to(
    coalesce(string_agg(x, chr(30) ORDER BY x COLLATE "C"), ''), 'UTF8')), 'hex') AS drift_digest
FROM (
  SELECT 'c' || chr(31) || c.relname || chr(31) || coalesce(c.relacl::text, '\N') AS x
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'research'
  UNION ALL
  SELECT 'p' || chr(31) || p.proname || chr(31)
         || pg_get_function_identity_arguments(p.oid) || chr(31)
         || coalesce(p.proacl::text, '\N')
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'research'
  UNION ALL
  SELECT 'n' || chr(31) || n.nspname || chr(31) || coalesce(n.nspacl::text, '\N')
  FROM pg_namespace n WHERE n.nspname = 'research'
) t;


-- =====================================================================
-- G01 — DATABASE BASELINE AND VERSION GUARD        EV-BASELINE-001
-- =====================================================================
-- Proves: which server and database this evidence describes; that the
--         version floor for sha256()/prokind is met.
-- STOP IF version_guard = 'BLOCKED'.
SELECT
  'EV-BASELINE-001'                                 AS evidence_set,
  current_database()                                AS database_name,
  current_setting('server_version')                 AS server_version,
  current_setting('server_version_num')::int        AS server_version_num,
  CASE WHEN current_setting('server_version_num')::int >= 110000
       THEN 'OK' ELSE 'BLOCKED' END                 AS version_guard,
  current_setting('lc_collate')                     AS lc_collate,
  current_setting('lc_ctype')                       AS lc_ctype,
  current_user                                      AS captured_by,
  (SELECT rolsuper FROM pg_roles WHERE rolname = current_user) AS captured_by_is_superuser,
  current_setting('transaction_read_only')          AS txn_read_only;

-- Self-test of the digest primitive. MUST return exactly
--   e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855
-- Any other value means the digest implementation is defective and the
-- whole evidence pack is void.
SELECT
  'EV-BASELINE-001'                                 AS evidence_set,
  'empty_digest_selftest'                           AS check_name,
  encode(sha256(''::bytea), 'hex')                  AS actual,
  'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855' AS expected,
  (encode(sha256(''::bytea), 'hex')
   = 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855') AS pass;


-- =====================================================================
-- G02 — ROLES AND ATTRIBUTES                       EV-ROLE-001
-- =====================================================================
-- Proves: the complete role population, including built-in pg_* roles.
-- pg_* roles are NOT excluded: pg_read_all_data / pg_write_all_data
-- (PG14+) confer effective access and are load-bearing for this boundary.
-- Row key: rolname
SELECT
  'EV-ROLE-001'                                     AS evidence_set,
  r.rolname                                         AS row_key,
  r.rolname,
  r.rolcanlogin,
  r.rolinherit,
  r.rolsuper,
  r.rolcreaterole,
