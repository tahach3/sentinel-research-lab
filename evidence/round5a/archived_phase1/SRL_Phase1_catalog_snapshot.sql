-- =====================================================================
-- G06 — FUNCTION INVENTORY                         EV-FUNCTION-001
-- =====================================================================
-- Proves: the exact schema-8 function population, settling the disputed
--         "54 functions" claim. Population membership is explicit on three
--         axes so the count is reproducible:
--           prokind             f=function p=procedure a=aggregate w=window
--           is_extension_member true => owned by an extension (e.g. vector);
--                               MUST NOT be frozen or revoked
--           returns_trigger     trigger functions, distinct freeze semantics
-- Every overload is a separate row; identity is
--   (schema, name, pg_get_function_identity_arguments) which is unique in PG.
-- OID is reported for cross-referencing within this snapshot ONLY. It is
-- excluded from row_key and from every digest: OIDs are not stable across
-- dump/restore.
-- Row key: schema.name(identity_args)
SELECT
  'EV-FUNCTION-001'                                 AS evidence_set,
  n.nspname || '.' || p.proname || '('
    || pg_get_function_identity_arguments(p.oid) || ')' AS row_key,
  p.oid                                             AS function_oid_unstable,
  n.nspname                                         AS schema_name,
  p.proname                                         AS function_name,
  pg_get_function_identity_arguments(p.oid)         AS identity_args,
  pg_get_function_result(p.oid)                     AS result_type,
  pg_get_userbyid(p.proowner)                       AS owner,
  l.lanname                                         AS language,
  p.prokind,
  CASE WHEN p.prosecdef THEN 'DEFINER' ELSE 'INVOKER' END AS security_mode,
  p.provolatile,
  p.proleakproof,
  (p.prorettype = 'pg_catalog.trigger'::regtype)    AS returns_trigger,
  EXISTS (SELECT 1 FROM pg_depend d
          WHERE d.classid = 'pg_proc'::regclass
            AND d.objid = p.oid AND d.deptype = 'e') AS is_extension_member,
  (p.proacl IS NULL)                                AS acl_is_default,
  coalesce(p.proacl::text, '\N')                    AS raw_proacl
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
JOIN pg_language  l ON l.oid = p.prolang
WHERE n.nspname = 'research'
ORDER BY n.nspname COLLATE "C",
         p.proname COLLATE "C",
         pg_get_function_identity_arguments(p.oid) COLLATE "C";

-- Population counts, so the disputed number is stated as a derived fact.
SELECT
  'EV-FUNCTION-002'                                 AS evidence_set,
  p.prokind,
  EXISTS (SELECT 1 FROM pg_depend d
          WHERE d.classid = 'pg_proc'::regclass
            AND d.objid = p.oid AND d.deptype = 'e') AS is_extension_member,
  (p.prorettype = 'pg_catalog.trigger'::regtype)    AS returns_trigger,
  count(*)                                          AS function_count
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = 'research'
GROUP BY 2, 3, 4, p.prokind
ORDER BY p.prokind COLLATE "C", 3, 4;


-- =====================================================================
-- G07 — FUNCTION ACLS, DIRECT AND DEFAULT          EV-FUNCTION-ACL-001
-- =====================================================================
-- *** THIS QUERY IS THE ONE THAT SETTLES CODEX FINDING #1. ***
--
-- proacl IS NULL does NOT mean "no grants". It means the built-in default
-- applies, and for functions that default is:
--       =X/owner        -> PUBLIC HOLDS EXECUTE
--       owner=X/owner   -> owner holds EXECUTE
-- Revision 7 asserts PUBLIC EXECUTE = N for all 54 functions. If any function
-- has proacl IS NULL, that assertion is false for that function.
--
-- grantee = 0 in aclexplode() output is PUBLIC. It renders as '-' under
-- ::regrole and errors or misleads under pg_get_userbyid(0), so it is
-- CASE-handled explicitly.
--
-- LEFT JOIN ... ON TRUE is required: a function whose proacl is an explicitly
-- empty array '{}' (everything revoked) yields zero aclexplode rows and would
-- silently vanish from the inventory under an inner join.
-- Row key: schema.name(identity_args)|grantee|privilege
SELECT
  'EV-FUNCTION-ACL-001'                             AS evidence_set,
  n.nspname || '.' || p.proname || '('
    || pg_get_function_identity_arguments(p.oid) || ')'
    || '|' || coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                            ELSE pg_get_userbyid(a.grantee) END, '\N')
    || '|' || coalesce(a.privilege_type, '\N')      AS row_key,
  n.nspname                                         AS schema_name,
  p.proname                                         AS function_name,
  pg_get_function_identity_arguments(p.oid)         AS identity_args,
  pg_get_userbyid(p.proowner)                       AS owner,
  (p.proacl IS NULL)                                AS acl_is_default,
  CASE WHEN p.proacl IS NULL
       THEN 'DEFAULT_EXPANDED_acldefault(f,owner)'
       ELSE 'EXPLICIT_proacl' END                   AS acl_source,
  CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantee) END AS grantee,
  (a.grantee = 0)                                   AS grantee_is_public,
  (a.grantee = p.proowner)                          AS grantee_is_owner,
  CASE WHEN a.grantor = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantor) END AS grantor,
  a.privilege_type,
  a.is_grantable
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
LEFT JOIN LATERAL aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a ON TRUE
WHERE n.nspname = 'research'
ORDER BY n.nspname COLLATE "C",
         p.proname COLLATE "C",
         pg_get_function_identity_arguments(p.oid) COLLATE "C",
         coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                       ELSE pg_get_userbyid(a.grantee) END, '') COLLATE "C",
         coalesce(a.privilege_type, '') COLLATE "C";

-- Direct contradiction test against Revision 7 §13.3.
-- Any row returned here falsifies "PUBLIC EXECUTE = N for all functions".
SELECT
  'EV-FUNCTION-ACL-002'                             AS evidence_set,
  n.nspname || '.' || p.proname || '('
    || pg_get_function_identity_arguments(p.oid) || ')' AS row_key,
  (p.proacl IS NULL)                                AS acl_is_default,
  'PUBLIC holds EXECUTE — contradicts Rev7 §13.3 PUBLIC EXECUTE = N' AS finding
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
CROSS JOIN LATERAL aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
WHERE n.nspname = 'research'
  AND a.grantee = 0
  AND a.privilege_type = 'EXECUTE'
ORDER BY 2 COLLATE "C";


-- =====================================================================
-- G08 — EFFECTIVE FUNCTION EXECUTE, ALL ROLES      EV-FUNCTION-EXEC-001
-- =====================================================================
-- Cross product of every function with EVERY role in the cluster — not the
-- five roles Revision 7 assumes. Five boolean columns decompose the single
-- word "effective" into its distinct meanings:
--
--   granted_direct        an ACL row names this role explicitly
--   granted_via_public    an ACL row names PUBLIC
--   granted_via_inherit   an ACL row names a role this role inherits (auto)
--   set_role_only         reachable only after SET ROLE (NOINHERIT member)
--   superuser_derived     role is superuser; has_*_privilege is true always
--
--   effective_execute     has_function_privilege() — the server's own answer
--   exercisable           effective_execute AND schema USAGE
--
-- has_function_privilege() does NOT check schema USAGE. A role with EXECUTE
-- but no USAGE on `research` cannot call the function. Freeze scope must be
-- driven by `exercisable`, not by `effective_execute`.
-- Row key: schema.name(identity_args)|role
SELECT
  'EV-FUNCTION-EXEC-001'                            AS evidence_set,
  fn.row_key || '|' || r.rolname                    AS row_key,
  fn.schema_name,
  fn.function_name,
  fn.identity_args,
  r.rolname,
  r.rolcanlogin,
  r.rolinherit,
  r.rolsuper                                        AS superuser_derived,
  has_function_privilege(r.oid, fn.oid, 'EXECUTE')  AS effective_execute,
  has_schema_privilege(r.oid, 'research', 'USAGE')  AS schema_usage,
  (has_function_privilege(r.oid, fn.oid, 'EXECUTE')
   AND has_schema_privilege(r.oid, 'research', 'USAGE')) AS exercisable,
  EXISTS (SELECT 1 FROM aclexplode(fn.eff_acl) a
          WHERE a.grantee = r.oid AND a.privilege_type = 'EXECUTE')  AS granted_direct,
  EXISTS (SELECT 1 FROM aclexplode(fn.eff_acl) a
          WHERE a.grantee = 0     AND a.privilege_type = 'EXECUTE')  AS granted_via_public,
  EXISTS (SELECT 1 FROM aclexplode(fn.eff_acl) a
          WHERE a.privilege_type = 'EXECUTE' AND a.grantee <> 0
            AND a.grantee <> r.oid
            AND pg_has_role(r.oid, a.grantee, 'USAGE'))              AS granted_via_inherit,
  EXISTS (SELECT 1 FROM aclexplode(fn.eff_acl) a
          WHERE a.privilege_type = 'EXECUTE' AND a.grantee <> 0
            AND a.grantee <> r.oid
            AND pg_has_role(r.oid, a.grantee, 'MEMBER')
            AND NOT pg_has_role(r.oid, a.grantee, 'USAGE'))          AS set_role_only
FROM (
  SELECT p.oid,
         n.nspname AS schema_name,
         p.proname AS function_name,
         pg_get_function_identity_arguments(p.oid) AS identity_args,
         n.nspname || '.' || p.proname || '('
           || pg_get_function_identity_arguments(p.oid) || ')' AS row_key,
         coalesce(p.proacl, acldefault('f', p.proowner)) AS eff_acl
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'research'
) fn
CROSS JOIN pg_roles r
ORDER BY fn.row_key COLLATE "C", r.rolname COLLATE "C";


-- =====================================================================
-- G09 — BASE TABLES AND OWNERS                     EV-TABLE-001
-- =====================================================================
-- relkind 'r' ordinary table, 'p' partitioned table. Both are base tables.
-- Row key: schema.table
SELECT
  'EV-TABLE-001'                                    AS evidence_set,
  n.nspname || '.' || c.relname                     AS row_key,
  c.oid                                             AS relation_oid_unstable,
  n.nspname                                         AS schema_name,
  c.relname                                         AS table_name,
  c.relkind,
  pg_get_userbyid(c.relowner)                       AS owner,
  c.relrowsecurity,
  c.relforcerowsecurity,
  (c.relacl IS NULL)                                AS acl_is_default,
  coalesce(c.relacl::text, '\N')                    AS raw_relacl
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'research' AND c.relkind IN ('r', 'p')
ORDER BY n.nspname COLLATE "C", c.relname COLLATE "C";


-- =====================================================================
-- G10 — RELATION ACLS, DIRECT AND DEFAULT          EV-TABLE-ACL-001
-- =====================================================================
-- relacl IS NULL expands via acldefault('r', owner): owner holds ALL,
-- PUBLIC holds NOTHING. This is the OPPOSITE of the function default and
-- must not be conflated with it.
-- Row key: schema.table|grantee|privilege
SELECT
  'EV-TABLE-ACL-001'                                AS evidence_set,
  n.nspname || '.' || c.relname
    || '|' || coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                            ELSE pg_get_userbyid(a.grantee) END, '\N')
    || '|' || coalesce(a.privilege_type, '\N')      AS row_key,
  n.nspname                                         AS schema_name,
  c.relname                                         AS table_name,
  pg_get_userbyid(c.relowner)                       AS owner,
  (c.relacl IS NULL)                                AS acl_is_default,
  CASE WHEN c.relacl IS NULL
       THEN 'DEFAULT_EXPANDED_acldefault(r,owner)'
       ELSE 'EXPLICIT_relacl' END                   AS acl_source,
  CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantee) END AS grantee,
  (a.grantee = 0)                                   AS grantee_is_public,
  (a.grantee = c.relowner)                          AS grantee_is_owner,
  a.privilege_type,
  a.is_grantable
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN LATERAL aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) a ON TRUE
WHERE n.nspname = 'research' AND c.relkind IN ('r', 'p')
ORDER BY n.nspname COLLATE "C", c.relname COLLATE "C",
         coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                       ELSE pg_get_userbyid(a.grantee) END, '') COLLATE "C",
         coalesce(a.privilege_type, '') COLLATE "C";


-- =====================================================================
-- G11 — EFFECTIVE TABLE WRITE MATRIX               EV-TABLE-WRITE-001
-- =====================================================================
-- *** THIS QUERY IS THE ONE THAT SETTLES CODEX FINDING #2. ***
--
-- Every base table crossed with EVERY role and every privilege — replacing
-- Revision 7's five-role matrix and its uniform "DELETE = Y" claim.
-- Same five-way decomposition of "effective" as G08.
-- Row key: schema.table|role|privilege
SELECT
  'EV-TABLE-WRITE-001'                              AS evidence_set,
  t.row_key || '|' || r.rolname || '|' || pr.priv   AS row_key,
  t.schema_name,
  t.table_name,
  t.owner,
  r.rolname,
  r.rolcanlogin,
  r.rolinherit,
  r.rolsuper                                        AS superuser_derived,
  pr.priv                                           AS privilege,
  has_table_privilege(r.oid, t.oid, pr.priv)        AS effective_privilege,
  has_schema_privilege(r.oid, 'research', 'USAGE')  AS schema_usage,
  (has_table_privilege(r.oid, t.oid, pr.priv)
   AND has_schema_privilege(r.oid, 'research', 'USAGE')) AS exercisable,
  (r.oid = t.relowner)                              AS role_is_owner,
  EXISTS (SELECT 1 FROM aclexplode(t.eff_acl) a
          WHERE a.grantee = r.oid AND a.privilege_type = pr.priv)   AS granted_direct,
  EXISTS (SELECT 1 FROM aclexplode(t.eff_acl) a
          WHERE a.grantee = 0     AND a.privilege_type = pr.priv)   AS granted_via_public,
  EXISTS (SELECT 1 FROM aclexplode(t.eff_acl) a
          WHERE a.privilege_type = pr.priv AND a.grantee <> 0
            AND a.grantee <> r.oid
            AND pg_has_role(r.oid, a.grantee, 'USAGE'))             AS granted_via_inherit,
  EXISTS (SELECT 1 FROM aclexplode(t.eff_acl) a
          WHERE a.privilege_type = pr.priv AND a.grantee <> 0
            AND a.grantee <> r.oid
            AND pg_has_role(r.oid, a.grantee, 'MEMBER')
            AND NOT pg_has_role(r.oid, a.grantee, 'USAGE'))         AS set_role_only
FROM (
  SELECT c.oid, c.relowner,
         n.nspname AS schema_name, c.relname AS table_name,
         pg_get_userbyid(c.relowner) AS owner,
         n.nspname || '.' || c.relname AS row_key,
         coalesce(c.relacl, acldefault('r', c.relowner)) AS eff_acl
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'research' AND c.relkind IN ('r', 'p')
) t
CROSS JOIN pg_roles r
CROSS JOIN LATERAL (VALUES ('SELECT'),('INSERT'),('UPDATE'),('DELETE'),
                           ('TRUNCATE'),('REFERENCES'),('TRIGGER')) AS pr(priv)
ORDER BY t.row_key COLLATE "C", r.rolname COLLATE "C", pr.priv COLLATE "C";

