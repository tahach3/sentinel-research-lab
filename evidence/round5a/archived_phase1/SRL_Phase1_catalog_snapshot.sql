-- =====================================================================
-- G12 — COLUMN ACLS                                EV-COLUMN-ACL-001
-- =====================================================================
-- IMPORTANT AND EASY TO GET BACKWARDS:
--   attacl IS NULL does NOT expand to a PUBLIC grant. acldefault('c', owner)
--   is the EMPTY acl. NULL attacl means "no column-specific grants exist;
--   access is governed entirely by the table-level ACL."
--   This is the opposite situation from proacl (G07) and conflating the two
--   produces errors in both directions.
--
-- Every non-dropped column is emitted, including those with no ACL, so the
-- ABSENCE of a column grant is provable rather than merely unstated.
-- Row key: schema.table.column|grantee|privilege
SELECT
  'EV-COLUMN-ACL-001'                               AS evidence_set,
  n.nspname || '.' || c.relname || '.' || att.attname
    || '|' || coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                            ELSE pg_get_userbyid(a.grantee) END, '\N')
    || '|' || coalesce(a.privilege_type, '\N')      AS row_key,
  n.nspname                                         AS schema_name,
  c.relname                                         AS table_name,
  att.attnum                                        AS ordinal_position,
  att.attname                                       AS column_name,
  (att.attacl IS NULL)                              AS no_column_specific_acl,
  coalesce(att.attacl::text, '\N')                  AS raw_attacl,
  CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantee) END AS grantee,
  a.privilege_type,
  a.is_grantable
FROM pg_class c
JOIN pg_namespace n  ON n.oid = c.relnamespace
JOIN pg_attribute att ON att.attrelid = c.oid
LEFT JOIN LATERAL aclexplode(att.attacl) a ON TRUE   -- no acldefault: columns have none
WHERE n.nspname = 'research' AND c.relkind IN ('r', 'p')
  AND att.attnum > 0 AND NOT att.attisdropped
ORDER BY n.nspname COLLATE "C", c.relname COLLATE "C", att.attnum,
         coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                       ELSE pg_get_userbyid(a.grantee) END, '') COLLATE "C",
         coalesce(a.privilege_type, '') COLLATE "C";

-- Effective column privileges. has_column_privilege() correctly accounts for
-- table-level grants (a table UPDATE grant confers UPDATE on all columns), so
-- this is the authoritative answer to Revision 7's "UPDATE on all columns".
-- Restricted to roles that can log in or are reachable, to bound row count.
-- Row key: schema.table.column|role|privilege
SELECT
  'EV-COLUMN-EFF-001'                               AS evidence_set,
  n.nspname || '.' || c.relname || '.' || att.attname
    || '|' || r.rolname || '|' || pr.priv           AS row_key,
  n.nspname                                         AS schema_name,
  c.relname                                         AS table_name,
  att.attname                                       AS column_name,
  att.attnum                                        AS ordinal_position,
  r.rolname,
  r.rolsuper                                        AS superuser_derived,
  pr.priv                                           AS privilege,
  has_column_privilege(r.oid, c.oid, att.attnum, pr.priv) AS effective_privilege,
  (att.attacl IS NOT NULL)                          AS has_column_specific_acl
FROM pg_class c
JOIN pg_namespace n   ON n.oid = c.relnamespace
JOIN pg_attribute att ON att.attrelid = c.oid
CROSS JOIN pg_roles r
CROSS JOIN LATERAL (VALUES ('SELECT'),('INSERT'),('UPDATE'),('REFERENCES')) AS pr(priv)
WHERE n.nspname = 'research' AND c.relkind IN ('r', 'p')
  AND att.attnum > 0 AND NOT att.attisdropped
  AND (r.rolcanlogin OR r.rolname IN ('research_app','n8n_app',
                                      'research_governance','research_test'))
ORDER BY n.nspname COLLATE "C", c.relname COLLATE "C", att.attnum,
         r.rolname COLLATE "C", pr.priv COLLATE "C";


