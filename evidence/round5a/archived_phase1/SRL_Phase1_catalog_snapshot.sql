-- =====================================================================
-- G03 — ROLE MEMBERSHIP GRAPH (TRANSITIVE)         EV-ROLE-002
-- =====================================================================
-- Proves: every path by which a role acquires another role's privileges,
--         and whether that path is automatic (INHERIT) or requires SET ROLE.
-- inherited_auto  : privileges apply without action  -> pg_has_role(...,'USAGE')
-- set_role_only   : privileges reachable via SET ROLE -> 'MEMBER' but not 'USAGE'
-- A NOINHERIT role showing set_role_only = true is still a live write path
-- and must appear in the boundary analysis.
-- Row key: member_role|granted_role|depth
WITH RECURSIVE mem AS (
  SELECT am.member AS member_oid, am.roleid AS role_oid, 1 AS depth,
         ARRAY[am.roleid] AS path
  FROM pg_auth_members am
  UNION ALL
  SELECT m.member_oid, am.roleid, m.depth + 1, m.path || am.roleid
  FROM mem m
  JOIN pg_auth_members am ON am.member = m.role_oid
  WHERE NOT am.roleid = ANY(m.path)          -- cycle guard
    AND m.depth < 32                         -- runaway guard
)
SELECT
  'EV-ROLE-002'                                     AS evidence_set,
  mr.rolname || '|' || gr.rolname || '|' || mem.depth::text AS row_key,
  mr.rolname                                        AS member_role,
  gr.rolname                                        AS granted_role,
  mem.depth,
  mr.rolinherit                                     AS member_inherits,
  pg_has_role(mr.oid, gr.oid, 'USAGE')              AS inherited_auto,
  pg_has_role(mr.oid, gr.oid, 'MEMBER')             AS reachable_member,
  (pg_has_role(mr.oid, gr.oid, 'MEMBER')
   AND NOT pg_has_role(mr.oid, gr.oid, 'USAGE'))    AS set_role_only
FROM mem
JOIN pg_roles mr ON mr.oid = mem.member_oid
JOIN pg_roles gr ON gr.oid = mem.role_oid
ORDER BY mr.rolname COLLATE "C", gr.rolname COLLATE "C", mem.depth;


-- =====================================================================
-- G04 — SCHEMAS, OWNERS, SCHEMA ACLS               EV-SCHEMA-001
-- =====================================================================
-- NULL nspacl expansion: acldefault('n', owner) = owner holds USAGE+CREATE,
-- PUBLIC holds NOTHING. (The historical PUBLIC grant on schema `public` is
-- an explicit initdb grant, not a default, and PG15 removed CREATE from it.)
-- LEFT JOIN LATERAL ... ON TRUE so a fully-revoked schema still emits a row.
-- Row key: schema|grantee|privilege
SELECT
  'EV-SCHEMA-001'                                   AS evidence_set,
  n.nspname || '|' || coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                                    ELSE pg_get_userbyid(a.grantee) END, '\N')
            || '|' || coalesce(a.privilege_type, '\N')  AS row_key,
  n.nspname                                         AS schema_name,
  pg_get_userbyid(n.nspowner)                       AS owner,
  (n.nspacl IS NULL)                                AS acl_is_default,
  coalesce(n.nspacl::text, '\N')                    AS raw_nspacl,
  CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantee) END AS grantee,
  CASE WHEN a.grantor = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantor) END AS grantor,
  a.privilege_type,
  a.is_grantable
FROM pg_namespace n
LEFT JOIN LATERAL aclexplode(coalesce(n.nspacl, acldefault('n', n.nspowner))) a ON TRUE
WHERE n.nspname NOT LIKE 'pg\_%'
ORDER BY n.nspname COLLATE "C",
         coalesce(CASE WHEN a.grantee = 0 THEN 'PUBLIC'
                       ELSE pg_get_userbyid(a.grantee) END, '') COLLATE "C",
         coalesce(a.privilege_type, '') COLLATE "C";

-- Effective schema USAGE per role. This is the gate that has_table_privilege()
-- and has_function_privilege() do NOT check. Without USAGE on `research`,
-- a table or function privilege is unexercisable.
-- Row key: schema|role
SELECT
  'EV-SCHEMA-002'                                   AS evidence_set,
  n.nspname || '|' || r.rolname                     AS row_key,
  n.nspname                                         AS schema_name,
  r.rolname,
  r.rolsuper                                        AS superuser_derived,
  has_schema_privilege(r.oid, n.oid, 'USAGE')       AS effective_usage,
  has_schema_privilege(r.oid, n.oid, 'CREATE')      AS effective_create
FROM pg_namespace n
CROSS JOIN pg_roles r
WHERE n.nspname NOT LIKE 'pg\_%'
ORDER BY n.nspname COLLATE "C", r.rolname COLLATE "C";


